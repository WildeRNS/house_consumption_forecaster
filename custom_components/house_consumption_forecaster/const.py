"""Constants for House Consumption Forecaster."""
DOMAIN = "house_consumption_forecaster"

# Розмір ковзного вікна історії (днів), яке використовується для середнього
# споживання будинку та середньої сонячної генерації за останні HISTORY_DAYS днів.
HISTORY_DAYS = 10

# Мінімальне валідне значення добового споживання (кВт*год). Нижче цього
# значення день вважається помилковим показанням сенсора (а не "тихим"
# днем) і не потрапляє в історію. Навмисно низьке, щоб не відкидати
# легітимні дні з малим споживанням (напр. відсутність вдома) -- саме
# відкидання таких днів раніше й зміщувало середнє вгору.
MIN_VALID_CONSUMPTION = 1.0

# Межі коефіцієнта зміщення (bias correction). Симетричні відносно 1.0:
# прогноз може бути скоригований максимум на +-15%. Раніше межі були
# асиметричними (0.85 - 1.25), тобто модель могла завищувати прогноз
# сильніше (+25%), ніж занижувати (-15%) -- це і було системною причиною
# завищення.
BIAS_MIN = 0.85
BIAS_MAX = 1.15
BIAS_MAX_DAILY_STEP = 0.03

# Межі ваги сонячної кореляції. Це вже не "кВт*год сонця", а частка
# середнього споживання за розрахунковий період (HISTORY_DAYS днів), на яку прогноз змінюється при відхиленні
# сонячної генерації від її власного середнього. Нижня межа тепер 0 (не
# 0.05), щоб самонавчання могло повністю прибрати вплив сонця, якщо
# кореляція виявиться відсутньою чи хибною.
SOLAR_WEIGHT_MIN = 0.0
SOLAR_WEIGHT_MAX = 0.30
SOLAR_WEIGHT_MAX_DAILY_STEP = 0.02

# Межі відносного коефіцієнта сонячної генерації (прогноз / середнє за
# HISTORY_DAYS днів). Обмежують, наскільки "дуже сонячний" або "дуже
# похмурий" день може вплинути на прогноз за одну ітерацію.
SOLAR_RATIO_MIN = 0.3
SOLAR_RATIO_MAX = 2.0

# Межі температурних коефіцієнтів (кВт*год на градус відхилення).
TEMP_COEFF_MIN = 0.0
TEMP_COEFF_MAX = 1.2
TEMP_COEFF_MAX_DAILY_STEP = 0.03

# Максимальний внесок температурної корекції як частка від середнього
# споживання за розрахунковий період -- захист від "розгону" прогнозу в
# дуже спекотну/холодну погоду.
MAX_TEMP_EFFECT_RATIO = 0.35

# Абсолютні захисні межі прогнозу відносно середнього споживання за
# розрахунковий період (HISTORY_DAYS днів).
# Раніше була лише підлога (0.85x) і жодної стелі -- прогноз міг тільки
# зростати. Тепер симетрично обмежений з обох боків.
FORECAST_FLOOR_RATIO = 0.5
FORECAST_CEILING_RATIO = 1.6

