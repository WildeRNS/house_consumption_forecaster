"""Constants for House Consumption Forecaster."""
DOMAIN = "house_consumption_forecaster"

# Скільки днів історії фактично зберігати на диску -- незалежно від того,
# який період усереднення користувач обрав у налаштуваннях. Завдяки цьому
# зміна періоду усереднення (CONF_HISTORY_DAYS) в Options діє миттєво, без
# очікування накопичення нових днів, бо потрібні дані вже збережені.
HISTORY_STORAGE_CAP = 30

# Період усереднення (днів), який користувач може змінити в UI (Options).
# DEFAULT застосовується, доки користувач явно не змінить значення.
DEFAULT_HISTORY_DAYS = 10
MIN_HISTORY_DAYS = 3
MAX_HISTORY_DAYS = HISTORY_STORAGE_CAP

# Мінімальне валідне значення добового споживання (кВт*год). Нижче цього
# значення день вважається помилковим показанням сенсора (а не "тихим"
# днем) і не потрапляє в історію.
MIN_VALID_CONSUMPTION = 1.0

# Межі коефіцієнта зміщення (bias correction). Симетричні відносно 1.0.
# Розширено до +-25% (було +-15%): попередня версія з вужчими межами не
# встигала "наздогнати" реальний рівень споживання, коли він стабільно і
# суттєво падав (напр. сезонно чи через зміну звичок) швидше, ніж встигало
# зміститись ковзне середнє. Межі лишаються СИМЕТРИЧНИМИ в обидва боки --
# модель не може завищувати легше, ніж занижувати.
BIAS_MIN = 0.75
BIAS_MAX = 1.25
BIAS_MAX_DAILY_STEP = 0.04

# Межі ваги сонячної кореляції. Це частка середнього споживання за період,
# на яку прогноз змінюється при відхиленні сонячної генерації від її
# власного середнього. Може обнулитись повністю, якщо кореляції немає.
SOLAR_WEIGHT_MIN = 0.0
SOLAR_WEIGHT_MAX = 0.30
SOLAR_WEIGHT_MAX_DAILY_STEP = 0.02

# Межі відносного коефіцієнта сонячної генерації (прогноз / середнє за
# обраний період). Обмежують, наскільки "дуже сонячний" або "дуже
# похмурий" день може вплинути на прогноз за одну ітерацію.
SOLAR_RATIO_MIN = 0.3
SOLAR_RATIO_MAX = 2.0

# Межі температурних коефіцієнтів (кВт*год на градус відхилення).
TEMP_COEFF_MIN = 0.0
TEMP_COEFF_MAX = 1.2
TEMP_COEFF_MAX_DAILY_STEP = 0.03

# Максимальний внесок температурної корекції як частка від середнього
# споживання за розрахунковий період -- захист від "розгону" прогнозу в
# дуже спекотну/холодну погоду.
MAX_TEMP_EFFECT_RATIO = 0.35

# Абсолютні захисні межі прогнозу відносно середнього споживання за
# розрахунковий період.
FORECAST_FLOOR_RATIO = 0.5
FORECAST_CEILING_RATIO = 1.6

# Config Flow keys
CONF_CONSUMPTION_SENSOR = "consumption_sensor"
CONF_SOLAR_ACTUAL_SENSOR = "solar_actual_sensor"
CONF_SOLAR_FORECAST_TODAY = "solar_forecast_today"
CONF_SOLAR_FORECAST_TOMORROW = "solar_forecast_tomorrow"
CONF_WEATHER_ENTITY = "weather_entity"
CONF_HISTORY_DAYS = "history_days"
